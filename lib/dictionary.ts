export function tCountry(value: string, lang: Lang): string {
  if (lang === "es") return value;
  return countryNames[value] ?? value;
}

export function tContinent(value: string, lang: Lang): string {
  if (lang === "es") return value;
  return continentNames[value] ?? value;
}

